#!/usr/bin/env python3
"""Compile GLSL shaders to SPIR-V and emit C++ headers.

Usage: compile_shaders.py <glslangValidator> <out_dir> <shader>...

The build runs this automatically when glslangValidator is available (it
ships with the Vulkan SDK and most Linux distros). The generated headers are
also checked in under shaders/prebuilt so the game builds without it.
"""
import os
import subprocess
import sys
import tempfile


def main() -> int:
    glslang, out_dir, *shaders = sys.argv[1:]
    os.makedirs(out_dir, exist_ok=True)
    for src in shaders:
        name = os.path.basename(src).replace(".", "_")
        with tempfile.TemporaryDirectory() as tmp:
            spv = os.path.join(tmp, name + ".spv")
            subprocess.run([glslang, "-V", "--target-env", "vulkan1.3", "-o", spv, src], check=True,
                           stdout=subprocess.DEVNULL)
            data = open(spv, "rb").read()
        words = [int.from_bytes(data[i:i + 4], "little") for i in range(0, len(data), 4)]
        body = ",\n".join("    " + ", ".join(f"0x{w:08x}" for w in words[i:i + 8]) for i in range(0, len(words), 8))
        header = (f"// Generated by tools/compile_shaders.py from {os.path.basename(src)}. Do not edit.\n"
                  f"#pragma once\n#include <cstdint>\n\n"
                  f"inline constexpr uint32_t k_{name}[] = {{\n{body}\n}};\n")
        path = os.path.join(out_dir, name + ".h")
        if not os.path.exists(path) or open(path).read() != header:
            open(path, "w").write(header)
    return 0


if __name__ == "__main__":
    sys.exit(main())
